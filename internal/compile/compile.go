// Package compile parses BetterGo, lowers it to Go, and formats .bgo sources.
package compile

import (
	"bytes"
	"fmt"
	"go/ast"
	goparser "go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"bettergo/internal/lower"
	"bettergo/internal/parser"
	"bettergo/internal/syntax"
)

// Result is a parsed and lowered BetterGo file.
type Result struct {
	Fset    *token.FileSet
	File    *ast.File
	Go      []byte
	Diags   []lower.Error
	AbsPath string
}

// ParseLower parses src as BetterGo and lowers ternaries to Go.
// filename should be absolute so //line directives point at the .bgo file.
func ParseLower(filename string, src []byte) (*Result, error) {
	abs := filename
	if a, err := filepath.Abs(filename); err == nil {
		abs = a
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, abs, src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	diags := lower.File(fset, file)
	goSrc, err := printGo(fset, file)
	if err != nil {
		return nil, err
	}
	return &Result{Fset: fset, File: file, Go: goSrc, Diags: diags, AbsPath: abs}, nil
}

func printGo(fset *token.FileSet, file *ast.File) ([]byte, error) {
	var buf bytes.Buffer
	cfg := printer.Config{Mode: printer.UseSpaces | printer.TabIndent | printer.SourcePos, Tabwidth: 8}
	if err := cfg.Fprint(&buf, fset, file); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by bettergo; DO NOT EDIT.\n\n")
	out.Write(buf.Bytes())
	return out.Bytes(), nil
}

// Generate reads a .bgo file and writes the sibling .go file.
func Generate(path string) (*Result, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	res, err := ParseLower(path, src)
	if err != nil {
		return nil, err
	}
	out := strings.TrimSuffix(path, filepath.Ext(path)) + ".go"
	if err := os.WriteFile(out, res.Go, 0o644); err != nil {
		return nil, err
	}
	return res, diagsError(res.Diags)
}

func diagsError(diags []lower.Error) error {
	if len(diags) == 0 {
		return nil
	}
	var b strings.Builder
	for i, d := range diags {
		if i > 0 {
			b.WriteByte('\n')
		}
		b.WriteString(d.Error())
	}
	return fmt.Errorf("%s", b.String())
}

// Format formats BetterGo source, keeping ternary syntax.
func Format(src []byte) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "f.bgo", src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := printer.Fprint(&buf, fset, file); err != nil {
		return nil, err
	}
	out := buf.Bytes()
	for bytes.Contains(out, []byte(syntax.TernaryFunc+"(")) {
		next, ok, err := restoreTernaries(out)
		if err != nil || !ok {
			return nil, err
		}
		out = next
	}
	if !bytes.HasSuffix(out, []byte("\n")) {
		out = append(out, '\n')
	}
	return out, nil
}

func restoreTernaries(src []byte) ([]byte, bool, error) {
	fset := token.NewFileSet()
	file, err := goparser.ParseFile(fset, "f.go", src, goparser.ParseComments)
	if err != nil {
		return nil, false, err
	}
	type rep struct {
		start, end int
		text       string
	}
	var reps []rep
	ast.Inspect(file, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		id, ok := call.Fun.(*ast.Ident)
		if !ok || id.Name != syntax.TernaryFunc || len(call.Args) != 3 {
			return true
		}
		if !ternaryLeaf(call) {
			return true
		}
		start := fset.Position(call.Pos()).Offset
		end := fset.Position(call.End()).Offset
		if start < 0 || end > len(src) || start > end {
			return true
		}
		thenS := argText(src, fset, call.Args[0])
		condS := argText(src, fset, call.Args[1])
		elseS := argText(src, fset, call.Args[2])
		text := thenS + " if " + condS + " else " + elseS
		if needsParens(file, call) {
			text = "(" + text + ")"
		}
		reps = append(reps, rep{start, end, text})
		return true
	})
	if len(reps) == 0 {
		return src, false, nil
	}
	sort.Slice(reps, func(i, j int) bool { return reps[i].start > reps[j].start })
	out := append([]byte(nil), src...)
	for _, r := range reps {
		out = append(out[:r.start], append([]byte(r.text), out[r.end:]...)...)
	}
	return out, true, nil
}

func ternaryLeaf(call *ast.CallExpr) bool {
	leaf := true
	ast.Inspect(call, func(n ast.Node) bool {
		if n == call {
			return true
		}
		c, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		id, ok := c.Fun.(*ast.Ident)
		if ok && id.Name == syntax.TernaryFunc {
			leaf = false
		}
		return leaf
	})
	return leaf
}

func argText(src []byte, fset *token.FileSet, e ast.Expr) string {
	s := fset.Position(e.Pos()).Offset
	end := fset.Position(e.End()).Offset
	if s < 0 || end > len(src) || s > end {
		return ""
	}
	return string(src[s:end])
}

func needsParens(file *ast.File, call *ast.CallExpr) bool {
	parents := map[ast.Node]ast.Node{}
	var stack []ast.Node
	ast.Inspect(file, func(n ast.Node) bool {
		if n == nil {
			stack = stack[:len(stack)-1]
			return false
		}
		if len(stack) > 0 {
			parents[n] = stack[len(stack)-1]
		}
		stack = append(stack, n)
		return true
	})
	switch parents[call].(type) {
	case *ast.ParenExpr, *ast.AssignStmt, *ast.ReturnStmt, *ast.ExprStmt,
		*ast.ValueSpec, *ast.CallExpr, *ast.CompositeLit, *ast.SendStmt,
		*ast.CaseClause, *ast.KeyValueExpr:
		return false
	default:
		return true
	}
}
